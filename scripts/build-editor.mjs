#!/usr/bin/env node
/**
 * Build the vendored CodeMirror 6 chunk.
 *
 * The plugin is shipped without node_modules, so the generated
 * ui/client.editor.js is committed. Run this script after changing the
 * CodeMirror dependencies or scripts/editor-runtime.js.
 *
 * Usage: node scripts/build-editor.mjs [--check]
 */

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const entry = join(root, 'scripts/editor-runtime.js');
const target = join(root, 'ui/client.editor.js');
const licenseTarget = join(root, 'ui/codemirror-LICENSE');

const result = await build({
  entryPoints: [entry],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: 'es2019',
  write: false,
  minify: false,
  legalComments: 'inline',
});

const bundled = result.outputFiles[0].text.replace(/^[ \t]+$/gmu, '');
const banner = `/*! CodeMirror 6 — https://codemirror.net/6/ — MIT.
 * GENERATED by scripts/build-editor.mjs. Edit scripts/editor-runtime.js instead.
 */`;

const registration = `window.__ModuleLoader__.load({
  id: 'dsh-overleaf-workshop',
  chunk: 'client.editor.js',
  factory: function () { return window.__dshOverleafCodeMirror; },
});`;

const output = `${banner}
${bundled}
;
${registration}
`;

const packageRoot = (name) => {
  const directory = resolve(root, 'node_modules', name);
  if (!existsSync(join(directory, 'package.json'))) throw new Error(`could not locate package root for ${name}`);
  return directory;
};

const licensePackages = [
  '@codemirror/autocomplete',
  '@codemirror/commands',
  '@codemirror/language',
  '@codemirror/legacy-modes',
  '@codemirror/search',
  '@codemirror/state',
  '@codemirror/streamparser',
  '@codemirror/view',
  '@lezer/common',
  '@lezer/highlight',
  '@lezer/lr',
  '@marijn/find-cluster-break',
  'crelt',
  'style-mod',
  'w3c-keyname',
];
const license = `${licensePackages.map((name) => {
  const packageJson = JSON.parse(readFileSync(join(packageRoot(name), 'package.json'), 'utf8'));
  const text = readFileSync(join(packageRoot(name), 'LICENSE'), 'utf8').trim();
  return `----- ${name} ${packageJson.version} -----
${text}`;
}).join('\n\n')}
`;

if (output.split('__ModuleLoader__.load').length !== 2) {
  throw new Error('generated chunk must register exactly one module');
}
if (!output.includes("chunk: 'client.editor.js'")) throw new Error('generated chunk has the wrong chunk name');
if (!/version\s*:\s*["']6["']/.test(output)) throw new Error('generated chunk did not expose CodeMirror 6');

if (process.argv.includes('--check')) {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
  const currentLicense = existsSync(licenseTarget) ? readFileSync(licenseTarget, 'utf8') : '';
  if (current !== output || currentLicense !== license) {
    console.error('ui/client.editor.js or ui/codemirror-LICENSE is stale; run npm run build:editor');
    process.exit(1);
  }
  console.log('CodeMirror 6 chunk is up to date');
} else {
  writeFileSync(target, output);
  writeFileSync(licenseTarget, license);
  console.log(`wrote ui/client.editor.js (${output.length} bytes, CodeMirror 6)`);
  console.log('wrote ui/codemirror-LICENSE');
}
